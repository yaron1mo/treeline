class Canvas:
    def __init__(self, w, h, bg=(255,255,255)):
        self.w, self.h = w, h
        self.px = [[bg]*w for _ in range(h)]
    def put(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h: self.px[y][x] = c
    def rect(self, x, y, w, h, c, fill=True):
        for i in range(x, x+w):
            for j in range(y, y+h): self.put(i, j, c)
    def line(self, x0, y0, x1, y1, c, width=1):
        dx, dy = abs(x1-x0), abs(y1-y0)
        sx = 1 if x0 < x1 else -1; sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            for o in range(-(width//2), width//2+1):
                if dx >= dy: self.put(x0, y0+o, c)
                else: self.put(x0+o, y0, c)
            if x0 == x1 and y0 == y1: break
            e2 = 2*err
            if e2 > -dy: err -= dy; x0 += sx
            if e2 < dx: err += dx; y0 += sy
    def text(self, x, y, s, c=(0,0,0), scale=1):
        cx = x
        for ch in s.lower():
            g = FONT.get(ch, ["111","101","101","101","111"] if ch.isalpha() else ["000"]*5)
            gw = max(len(r) for r in g) if g else 3
            for j, row in enumerate(g):
                for i, b in enumerate(row):
                    if b == '1':
                        self.rect(cx+i*scale, y+j*scale, scale, scale, c)
            cx += (gw+1)*scale
    def save(self, path):
        raw = b''.join(b'\x00' + bytes(v for p in row for v in p) for row in self.px)
        def chunk(t, d):
            out = struct.pack('>I', len(d)) + t + d
            return out + struct.pack('>I', zlib.crc32(t+d) & 0xffffffff)
        png = b'\x89PNG\r\n\x1a\n'
        png += chunk(b'IHDR', struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0))
        png += chunk(b'IDAT', zlib.compress(raw, 6))
        png += chunk(b'IEND', b'')
        open(path, 'wb').write(png)
